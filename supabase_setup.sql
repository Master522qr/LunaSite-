create or replace function public.handle_lunavisual_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, email, mc_nickname, is_admin)
  values (
    new.id,
    new.email,
    coalesce(new.raw_user_meta_data->>'mc_nickname', split_part(new.email, '@', 1)),
    lower(coalesce(new.email, '')) = 'bobretor10@gmail.com'
  )
  on conflict (id) do update set
    email = excluded.email,
    mc_nickname = coalesce(public.profiles.mc_nickname, excluded.mc_nickname),
    is_admin = public.profiles.is_admin or excluded.is_admin,
    updated_at = now();
  return new;
end;
$$;

