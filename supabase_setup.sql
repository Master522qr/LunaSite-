-- IMPORTANT: key generation is tied only to Supabase WEBSITE authentication.
-- The LunaVisual launcher intentionally has no separate registration requirement.
-- Users register on the website; generated keys can then be entered in the launcher.
create or replace function public.generate_lunavisual_keys(
  p_count integer,
  p_duration_days integer default 30
)
returns setof public.license_keys
language plpgsql
security definer
set search_path = public
as $$
declare
  i integer;
  v_code text;
  v_row public.license_keys%rowtype;
begin
  if not public.is_lunavisual_admin() then
    raise exception 'admin_required';
  end if;
  if not public.check_lunavisual_rate_limit('generate_keys', 12, 60) then
    raise exception 'rate_limited';
  end if;
  if p_count is null or p_count < 1 or p_count > 1000 then
    raise exception 'count_must_be_between_1_and_1000_per_batch';
  end if;
  if p_duration_days is null or p_duration_days < 1 then
    raise exception 'duration_must_be_positive';
  end if;

  for i in 1..p_count loop
    loop
      v_code := 'LUNAVISUALKEY-' ||
        lpad(floor(random()*10000)::int::text, 4, '0') || '-' ||
        lpad(floor(random()*10000)::int::text, 4, '0') || '-' ||
        lpad(floor(random()*10000)::int::text, 4, '0') || '-' ||
        lpad(floor(random()*10000)::int::text, 4, '0') || '-' ||
        lpad(floor(random()*10000)::int::text, 4, '0');
      begin
        insert into public.license_keys(code, duration_days, created_by)
        values (v_code, p_duration_days, auth.uid())
        returning * into v_row;
        exit;
      exception when unique_violation then
        -- collision: generate another code
      end;
    end loop;
    return next v_row;
  end loop;
end;
$$;

grant execute on function public.generate_lunavisual_keys(integer, integer) to authenticated;

create or replace function public.redeem_lunavisual_key(p_code text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  k public.license_keys%rowtype;
  u auth.users%rowtype;
  v_until timestamptz;
  v_until_text text;
  v_nick text;
begin
  if auth.uid() is null then
    raise exception 'login_required';
  end if;
  if not public.check_lunavisual_rate_limit('redeem_key', 10, 60) then
    return jsonb_build_object('ok', false, 'error', 'rate_limited');
  end if;

  select * into k
  from public.license_keys
  where upper(code) = upper(trim(p_code))
  for update;

  if not found then
    return jsonb_build_object('ok', false, 'error', 'not_found');
  end if;
  if k.is_used then
    return jsonb_build_object('ok', false, 'error', 'used');
  end if;

  select * into u from auth.users where id = auth.uid();
  select coalesce(mc_nickname, split_part(coalesce(email, u.email), '@', 1))
    into v_nick from public.profiles where id = auth.uid();

  if k.duration_days >= 9000 then
    v_until_text := 'Навсегда (Lifetime)';
  else
    v_until := now() + make_interval(days => k.duration_days);
    v_until_text := 'до ' || to_char(v_until at time zone 'UTC', 'DD.MM.YYYY');
  end if;

  update public.license_keys
  set is_used = true,
      used_by = coalesce(v_nick, u.email),
      used_by_user_id = auth.uid(),
      used_at = now()
  where id = k.id;

  update public.profiles
  set subscription_active = true,
      subscription_until = v_until_text,
      updated_at = now()
  where id = auth.uid();

  return jsonb_build_object(
    'ok', true,
    'code', k.code,
    'duration_days', k.duration_days,
    'subscription_until', v_until_text
  );
end;
$$;

grant execute on function public.redeem_lunavisual_key(text) to authenticated;

create or replace function public.protect_lunavisual_profile_fields()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() = old.id
     and not public.is_lunavisual_admin()
     and current_user <> 'postgres'
     and (new.subscription_active is distinct from old.subscription_active
          or new.subscription_until is distinct from old.subscription_until
          or new.is_admin is distinct from old.is_admin) then
    raise exception 'protected_profile_fields';
  end if;
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists protect_lunavisual_profile_fields_trg on public.profiles;
create trigger protect_lunavisual_profile_fields_trg
before update on public.profiles
for each row execute procedure public.protect_lunavisual_profile_fields();


-- API for the LunaVisual launcher. The launcher signs in through Supabase Auth,
-- then calls this RPC to obtain only the current user's own license state.
create or replace function public.get_lunavisual_launcher_state()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  p public.profiles%rowtype;
  v_maintenance boolean;
begin
  if auth.uid() is null then
    raise exception 'login_required';
  end if;
  if not public.check_lunavisual_rate_limit('launcher_state', 120, 60) then
    raise exception 'rate_limited';
  end if;

  select * into p from public.profiles where id = auth.uid();
  if not found then
    raise exception 'profile_not_found';
  end if;

  select exists(select 1 from public.license_keys where code = 'MAINTENANCE_MODE')
    into v_maintenance;

  return jsonb_build_object(
    'user_id', p.id,
    'email', p.email,
    'nickname', p.mc_nickname,
    'hwid', p.hwid,
    'subscription_active', p.subscription_active,
    'subscription_until', p.subscription_until,
    'is_admin', public.is_lunavisual_admin(),
    'maintenance', v_maintenance
  );
end;
$$;

grant execute on function public.get_lunavisual_launcher_state() to authenticated;

