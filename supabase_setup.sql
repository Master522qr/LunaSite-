-- ---------------------------------------------------------------------------
-- Abuse / application-layer DDoS protection for Supabase RPC calls.
-- This does not replace a CDN/WAF for network-layer DDoS, but it prevents a
-- logged-in account from hammering expensive LunaVisual RPC functions.
-- ---------------------------------------------------------------------------
create table if not exists public.rpc_rate_limits (
  user_id uuid not null references auth.users(id) on delete cascade,
  action text not null,
  window_started_at timestamptz not null default now(),
  request_count integer not null default 0,
  primary key (user_id, action)
);

alter table public.rpc_rate_limits enable row level security;
revoke all on table public.rpc_rate_limits from anon, authenticated;

create or replace function public.check_lunavisual_rate_limit(
  p_action text,
  p_max_requests integer,
  p_window_seconds integer
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  v_now timestamptz := clock_timestamp();
  v_row public.rpc_rate_limits%rowtype;
begin
  if v_uid is null then
    raise exception 'login_required';
  end if;
  if p_action is null or length(trim(p_action)) = 0 then
    raise exception 'invalid_rate_limit_action';
  end if;
  if p_max_requests < 1 or p_window_seconds < 1 then
    raise exception 'invalid_rate_limit_config';
  end if;

  insert into public.rpc_rate_limits(user_id, action, window_started_at, request_count)
  values (v_uid, p_action, v_now, 1)
  on conflict (user_id, action) do nothing;

  select * into v_row
  from public.rpc_rate_limits
  where user_id = v_uid and action = p_action
  for update;

  if v_row.window_started_at + make_interval(secs => p_window_seconds) <= v_now then
    update public.rpc_rate_limits
    set window_started_at = v_now,
        request_count = 1
    where user_id = v_uid and action = p_action;
    return true;
  end if;

  if v_row.request_count >= p_max_requests then
    return false;
  end if;

  update public.rpc_rate_limits
  set request_count = request_count + 1
  where user_id = v_uid and action = p_action;

  return true;
end;
$$;

revoke all on function public.check_lunavisual_rate_limit(text, integer, integer) from public;
grant execute on function public.check_lunavisual_rate_limit(text, integer, integer) to authenticated;

